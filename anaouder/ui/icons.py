# Icons that keep their colors in dark mode.
# The other icons in "icons/toolbar/" are black and are turned white.
COLORED_ICONS = {"sparkles-yellow.png", "add_segment.png"}


def _is_dark_mode() -> bool:
    return QGuiApplication.styleHints().colorScheme() == Qt.ColorScheme.Dark


def _toolbar_icon(filename: str) -> QIcon:
    """
    Load an icon from "icons/toolbar/".
    These files are generated by "icons/normalize_icons.py".
    """
    path = get_resource_path(f"icons/toolbar/{filename}")
    if not _is_dark_mode():
        return QIcon(path)

    image = QImage(path).convertToFormat(QImage.Format.Format_ARGB32)
    if filename not in COLORED_ICONS:
        image.invertPixels(QImage.InvertMode.InvertRgb)
    icon = QIcon(QPixmap.fromImage(image))

    # Qt's automatic disabled look doesn't dim icons on a dark background
    disabled = QPixmap(image.size())
    disabled.fill(Qt.GlobalColor.transparent)
    painter = QPainter(disabled)
    painter.setOpacity(0.3)
    painter.drawImage(0, 0, image)
    painter.end()
    icon.addPixmap(disabled, QIcon.Mode.Disabled)
    return icon


